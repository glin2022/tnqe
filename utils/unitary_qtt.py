from functools import lru_cache

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F

from .qtt import contract_cores


def RY(theta):
    c = torch.cos(theta / 2)
    s = torch.sin(theta / 2)
    M = torch.stack([torch.stack([c, -s], dim=-1), torch.stack([s, c], dim=-1)], dim=-2)
    return M.to(torch.complex64)


def RZ(theta):
    e0 = torch.exp(-0.5j * theta)
    e1 = torch.exp(0.5j * theta)
    return torch.diag(torch.stack([e0, e1]).to(torch.complex64))


def U_from_RY_RZ(ry, rz):
    """Single-qubit gate RZ(rz) @ RY(ry)  (== Qiskit ``u(ry, rz, 0)`` up to global phase)."""
    return (RZ(rz) @ RY(ry)).to(torch.complex64)


def CNOT_2q_q0_controls_q1(device=None):
    """CNOT in the pair basis index ``b_q0 + 2*b_q1`` (q0 = control = LSB)."""
    U = torch.zeros((4, 4), dtype=torch.complex64, device=device)
    U[0, 0] = 1
    U[2, 2] = 1
    U[3, 1] = 1
    U[1, 3] = 1
    return U


@lru_cache(maxsize=None)
def _perm_1q(n, out_axis):
    perm = (out_axis,) + tuple(i for i in range(n) if i != out_axis) + tuple(range(n, 2 * n))
    inv = [0] * (2 * n)
    for i, a in enumerate(perm):
        inv[a] = i
    return perm, tuple(inv)


@lru_cache(maxsize=None)
def _perm_2q(n, out_axis_a, out_axis_b):
    perm = ((out_axis_a, out_axis_b)
            + tuple(i for i in range(n) if i not in (out_axis_a, out_axis_b))
            + tuple(range(n, 2 * n)))
    inv = [0] * (2 * n)
    for i, a in enumerate(perm):
        inv[a] = i
    return perm, tuple(inv)


def apply_1q_left(U, G, q, n):
    """U <- (G on OUTPUT qubit q) @ U for a (2^n, 2^n) matrix U (qubit 0 = LSB)."""
    dim = 2 ** n
    out_axis = n - 1 - q
    perm, inv = _perm_1q(n, out_axis)
    T = U.reshape([2] * n + [2] * n).permute(perm).contiguous()
    flat = G.to(U.dtype) @ T.reshape(2, -1)
    return flat.reshape(T.shape).permute(inv).contiguous().reshape(dim, dim)


def apply_2q_left(U, G2, q0, q1, n):
    """U <- (G2 on OUTPUT qubits (q0,q1)) @ U; G2 uses the basis index ``b_q0 + 2*b_q1``."""
    dim = 2 ** n
    out0 = n - 1 - q0
    out1 = n - 1 - q1
    perm, inv = _perm_2q(n, out1, out0)
    T = U.reshape([2] * n + [2] * n).permute(perm).contiguous()
    flat = G2.to(U.dtype) @ T.reshape(4, -1)
    return flat.reshape(T.shape).permute(inv).contiguous().reshape(dim, dim)


def block_unitary(theta, n_bond_qubits=3, n_layers=4, device=None):
    """Hardware-efficient block unitary on ``n_bond_qubits + 2`` qubits.

    ``theta`` has ``2 * (n_bond_qubits + 2) * n_layers`` entries ordered as
    (layer, qubit, [ry, rz]).  Qubits 0..n_b-1 are bond qubits, n_b and n_b+1 the physical ones.
    """
    theta = theta.to(device)
    n = n_bond_qubits + 2
    dim = 2 ** n
    U = torch.eye(dim, dtype=torch.complex64, device=device)
    CNOT = CNOT_2q_q0_controls_q1(device=device)
    phys0, phys1 = n_bond_qubits, n_bond_qubits + 1
    idx = 0
    for _ in range(n_layers):
        for q in range(n):
            U = apply_1q_left(U, U_from_RY_RZ(theta[idx], theta[idx + 1]), q, n)
            idx += 2
        for q in range(n_bond_qubits - 1):
            U = apply_2q_left(U, CNOT, q, q + 1, n)
        for q in range(n_bond_qubits):
            tgt = phys0 if (q % 2 == 0) else phys1
            U = apply_2q_left(U, CNOT, q, tgt, n)
        U = apply_2q_left(U, CNOT, phys0, phys1, n)
    return U


def unitary_to_core(U, rank):
    """First ``R`` columns of U (input bond state, physical input |00>) -> core (R,2,2,R).

    Row index of U is ``b + R * phys`` with ``phys = i + 2*j``;
    ``core[a, i, j, b] = U[b + R*(i+2j), a]``.
    """
    R = int(rank)
    V = U[:, 0:R].contiguous()
    V = V.reshape(4, R, R).permute(2, 0, 1)
    core = V.reshape(R, 2, 2, R)
    return core.permute(0, 2, 1, 3).contiguous()


def _is_power_of_two(x):
    return x > 0 and (x & (x - 1)) == 0


class QTTFromCircuit(nn.Module):
    """QTT whose cores are generated by ``L`` block unitaries (TNQE-unitary)."""

    def __init__(self, L=5, rank=8, n_layers_block=4, device="cpu"):
        super().__init__()
        if not _is_power_of_two(int(rank)):
            raise ValueError(f"rank must be a power of 2, got {rank}")
        self.L = int(L)
        self.rank = int(rank)
        self.n_bond_qubits = int(np.log2(self.rank))
        self.n_layers_block = int(n_layers_block)
        self.device = device
        self.params_per_block = 2 * (self.n_bond_qubits + 2) * self.n_layers_block
        self.theta = nn.Parameter(
            0.01 * torch.randn(self.L, self.params_per_block, dtype=torch.float32, device=device))

    @property
    def num_qubits(self):
        return self.n_bond_qubits + 2 * self.L

    def cores(self):
        cores = []
        for k in range(self.L):
            U = block_unitary(self.theta[k], self.n_bond_qubits, self.n_layers_block, self.device)
            cores.append(unitary_to_core(U, self.rank))
        cores[0] = cores[0][0:1]
        cores[-1] = cores[-1][:, :, :, 0:1]
        return cores

    def forward(self):
        return contract_cores(self.cores(), self.L)

    def theta_numpy(self):
        return self.theta.detach().cpu().numpy()


def born_image(X):
    """Born distribution p = |X|^2 / sum |X|^2 of a complex reconstruction."""
    p = torch.abs(X) ** 2
    return p / p.sum()


def train_unitary(target, rank=8, n_layers=4, steps=1000, max_lr=3e-2, weight_decay=1e-4,
                  grad_clip=1.0, loss_scale=1e3, hellinger_weight=0.1, device=None,
                  model=None, seed=None, verbose=False):
    """Train TNQE-unitary on ``target`` ((2^L,2^L) array in [0,1]).

    Returns (model, recon) where ``recon = p * sum(target)`` is the decoded image
    (probability convention, Appendix C).  Pass ``model`` to warm-start from a previous image.
    """
    if device is None:
        device = "cuda" if torch.cuda.is_available() else "cpu"
    if seed is not None:
        torch.manual_seed(int(seed))
    target_t = torch.as_tensor(np.asarray(target, dtype=np.float32), device=device)
    L = int(round(np.log2(target_t.shape[0])))
    if model is None:
        model = QTTFromCircuit(L=L, rank=rank, n_layers_block=n_layers, device=device).to(device)
    target_p = (target_t / target_t.sum()).detach()

    opt = torch.optim.AdamW(model.parameters(), lr=max_lr / 10.0, weight_decay=weight_decay)
    sched = torch.optim.lr_scheduler.OneCycleLR(
        opt, max_lr=max_lr, total_steps=steps, pct_start=0.1, div_factor=10.0,
        final_div_factor=100.0)
    for step in range(1, steps + 1):
        opt.zero_grad(set_to_none=True)
        p = born_image(model())
        loss_kl = F.kl_div(p.log(), target_p, reduction="batchmean")
        loss_h = F.mse_loss(torch.sqrt(p), torch.sqrt(target_p))
        loss = (loss_kl + hellinger_weight * loss_h) * loss_scale
        loss.backward()
        if grad_clip:
            torch.nn.utils.clip_grad_norm_(model.parameters(), grad_clip)
        opt.step()
        sched.step()
        if verbose and (step % max(1, steps // 10) == 0 or step == 1):
            print(f"  step={step:5d}  loss={loss.item():.4e}  kl={loss_kl.item():.4e}")
    with torch.no_grad():
        p = born_image(model())
        recon = (p * target_t.sum()).detach().cpu().numpy().astype(np.float64)
    return model, recon
